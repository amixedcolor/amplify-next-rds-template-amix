/**
 * Runtime checks for API arguments. TypeScript types don't exist at runtime, and
 * any client can send any JSON, so validate before using a value. Failures are
 * 400s; Blocks reserves JSON-RPC -32602 for its own protocol errors.
 */
import { ApiError } from '@aws-blocks/blocks';

function invalid(name: string, expected: string): never {
  throw new ApiError(`${name} must be ${expected}`, 400);
}

/** A trimmed, non-empty string of at most `maxLength` characters. */
export function requireText(value: unknown, name: string, maxLength: number): string {
  if (typeof value !== 'string') invalid(name, 'a string');
  const text = value.trim();
  if (!text || text.length > maxLength) invalid(name, `1-${maxLength} characters`);
  return text;
}

export function requireBoolean(value: unknown, name: string): boolean {
  if (typeof value !== 'boolean') invalid(name, 'a boolean');
  return value;
}

/** An ID as generated by crypto.randomUUID(). */
export function requireUuid(value: unknown, name: string): string {
  if (typeof value !== 'string' || !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)) {
    invalid(name, 'a UUID');
  }
  return value;
}
